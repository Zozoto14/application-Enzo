export const CLES_VOCAUX = Object.freeze(Object.keys(T.fr));

/** Texte fixe dans une langue (anglais pour toute autre langue que le français). */
export function tv(langue, cle, vars) {
  const l = langue === 'fr' ? 'fr' : 'en';
  return remplir(T[l][cle] ?? T.fr[cle] ?? cle, vars);
}

/** Texte publié dans le salon : les deux langues selon le réglage (`mode`), `langue` d'abord en mode « auteur ». */
export const tv2 = (cle, vars, opts) => bilingue(l => tv(l, cle, vars), opts);

/** Libellé court (boutons) : « Renommer · Rename » en deux langues, une seule en mode fr / en. */
export function libelleVocal(cle, { mode = 'auteur', langue = 'fr', max = 80 } = {}) {
  return [...new Set(ordreLangues(mode, langue).map(l => tv(l, cle)))].join(' · ').slice(0, max);
}
