/**
 * Adaptateur PostgreSQL (paquet `pg`) : même interface `base` que
 * SQLite (adaptateurs/sqlite.mjs), pour le serveur Node autonome
 * (esport/serveur/, hébergement o2switch ou tout serveur avec Postgres).
 *
 *   tous(sql, params)      → lignes (objets)
 *   premier(sql, params)   → première ligne ou null
 *   executer(sql, params)  → { changements }
 *   lot([{ sql, params }]) → [{ changements }], atomique (BEGIN / COMMIT)
 *   script(sql)            → plusieurs instructions (migrations seulement)
 *   fermer()               → ferme les connexions
 *
 * Le cœur (esport/noyau/) écrit du SQL standard pensé pour SQLite ET Postgres.
 * Les quelques différences restantes sont traitées ICI, une fois pour toutes,
 * pour que le cœur ne change pas (voir `traduireRequete`, `traduireMigration`) :
 *  - paramètres `?` → `$1, $2…` (hors chaînes, identifiants entre guillemets et commentaires) ; `? IS NULL`
 *    → `$1::text IS NULL` (Postgres ne devine pas le type d'un paramètre isolé) ;
 *  - `LIKE` → `ILIKE` (le LIKE de SQLite ignore la casse ASCII, celui de Postgres non) ;
 *  - alias en camelCase (`AS nbMembres`) mis entre guillemets (Postgres met sinon les noms en minuscules) ;
 *  - `INSERT OR IGNORE INTO …` → `INSERT INTO … ON CONFLICT DO NOTHING` (filet : le cœur ne l'emploie pas) ;
 *  - booléens rendus en 0/1 (comme SQLite), `COUNT(*)` / `SUM` (bigint, numeric) rendus en nombres ;
 *  - migrations : `INTEGER` → `BIGINT` (entiers 64 bits comme SQLite), `REAL` → `DOUBLE PRECISION`,
 *    `TEXT` → `TEXT COLLATE "C"` (tri et comparaisons octet par octet, comme SQLite, quelle que soit la
 *    langue de la base créée par cPanel), `AUTOINCREMENT` → identité (filet : le cœur ne l'emploie pas).
 * Les dates restent des textes ISO 8601 (UTC), les JSON des textes : rien à convertir.
 */

import { appliquerMigrations } from '../noyau/migrations.mjs';
import { lireMigrations } from './sqlite.mjs';

const normaliser = valeur => (valeur === undefined ? null : typeof valeur === 'boolean' ? (valeur ? 1 : 0) : valeur);

// ---------------------------------------------------------------- Traduction

const MOTS_ALIAS_INTERDITS = new Set(['null', 'true', 'false']);

/**
 * Parcourt `sql` en sautant les chaînes '…', les identifiants "…" et les commentaires,
 * et appelle `code(morceau)` sur chaque portion de code (hors chaînes) ; rend le texte recomposé.
 */
function surLeCode(sql, code) {
  let sortie = '';
  let morceau = '';
  let i = 0;
  const vider = () => {
    if (morceau) sortie += code(morceau);
    morceau = '';
  };
  while (i < sql.length) {
    const c = sql[i];
    if (c === "'" || c === '"') {
      vider();
      let j = i + 1;
      while (j < sql.length) {
        if (sql[j] === c) {
          if (sql[j + 1] === c) j += 2;
          else break;
        } else j++;
      }
      sortie += sql.slice(i, j + 1);
      i = j + 1;
    } else if (c === '-' && sql[i + 1] === '-') {
      vider();
      const fin = sql.indexOf('\n', i);
      const j = fin < 0 ? sql.length : fin;
      sortie += sql.slice(i, j);
      i = j;
    } else if (c === '/' && sql[i + 1] === '*') {
      vider();
      const fin = sql.indexOf('*/', i + 2);
      const j = fin < 0 ? sql.length : fin + 2;
      sortie += sql.slice(i, j);
      i = j;
    } else {
      morceau += c;
      i++;
    }
  }
  vider();
  return sortie;
}

/** Requête du cœur (dialecte commun SQLite/Postgres) → requête Postgres. */
export function traduireRequete(sql) {
  let n = 0;
  let ignorer = false;
  let texte = surLeCode(sql, code => {
    // `? IS NULL` : Postgres ne peut pas deviner le type d'un paramètre seul → typé en texte (tout type s'y convertit).
    let c = code.replace(/\?(\s+IS\s+(?:NOT\s+)?NULL\b)?/gi, (_, estNul) => (estNul ? `$${++n}::text${estNul}` : `$${++n}`));
    c = c.replace(/\bLIKE\b/gi, 'ILIKE');
    c = c.replace(/\bAS\s+([a-z_][a-z0-9_]*[A-Z][A-Za-z0-9_]*)\b/g, (tout, alias) => (MOTS_ALIAS_INTERDITS.has(alias.toLowerCase()) ? tout : `AS "${alias}"`));
    if (/\bINSERT\s+OR\s+IGNORE\s+INTO\b/i.test(c)) {
      ignorer = true;
      c = c.replace(/\bINSERT\s+OR\s+IGNORE\s+INTO\b/i, 'INSERT INTO');
    }
    return c;
  });
  if (ignorer && !/\bON\s+CONFLICT\b/i.test(texte)) texte = `${texte.replace(/;\s*$/, '')} ON CONFLICT DO NOTHING`;
  return texte;
}

/** Migration (DDL écrit pour SQLite et Postgres) → DDL Postgres. Ne touche ni aux chaînes ni aux commentaires. */
export function traduireMigration(sql) {
  return surLeCode(sql, code =>
    code
      .replace(/\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
      .replace(/\bAUTOINCREMENT\b/gi, '')
      .replace(/\bINTEGER\b/g, 'BIGINT')
      .replace(/\bREAL\b/g, 'DOUBLE PRECISION')
      .replace(/\bTEXT\b(?!\s+COLLATE)/g, 'TEXT COLLATE "C"'),
  );
}

// ---------------------------------------------------------------- Types rendus

/** Analyseurs de types : rendus identiques à SQLite (nombres, booléens 0/1). */
async function analyseurs() {
  const { default: pg } = await import('pg');
  const { types } = pg;
  const nombre = v => (v === null ? null : Number(v));
  const table = {
    20: nombre, // int8 (COUNT, SUM d'entiers, colonnes BIGINT)
    21: nombre, // int2
    23: nombre, // int4
    700: nombre, // float4
    701: nombre, // float8
    1700: nombre, // numeric (AVG, SUM)
    16: v => (v === null ? null : v === 't' || v === true ? 1 : 0), // bool → 0/1
  };
  return { pg, types: { getTypeParser: (oid, format) => table[oid] ?? types.getTypeParser(oid, format) } };
}

// ---------------------------------------------------------------- Connexion

/**
 * Configuration de connexion : `DATABASE_URL` (postgres://utilisateur:motdepasse@hote:5432/base)
 * ou les variables standard PGHOST, PGPORT, PGUSER, PGPASSWORD, PGDATABASE (lues par `pg` lui-même).
 */
export function configurationDepuisEnv(env = process.env) {
  if (env.DATABASE_URL) return { connectionString: env.DATABASE_URL };
  return {};
}

const MOTIF_SCHEMA = /^[a-z_][a-z0-9_]{0,62}$/;

/** Schéma des tables en production (SCHEMA_BASE, défaut « appdashboard ») : créé s'il manque. */
export const SCHEMA_PAR_DEFAUT = 'appdashboard';

/**
 * Options de connexion des serveurs (Esport, relais, cron, imports) depuis l'environnement : DATABASE_URL
 * ou PG*, schéma SCHEMA_BASE (défaut « appdashboard », créé au besoin). Un schéma à nous évite le schéma
 * `public`, fermé en écriture aux utilisateurs non propriétaires depuis PostgreSQL 15.
 */
export function optionsDepuisEnv(env = process.env) {
  return { ...(env.DATABASE_URL ? { connexion: env.DATABASE_URL } : {}), schema: env.SCHEMA_BASE || SCHEMA_PAR_DEFAUT, creerSchema: true };
}

/**
 * Ouvre une base Postgres. `connexion` : chaîne postgres://… ou objet de configuration `pg`
 * (défaut : variables d'environnement). `schema` : schéma de travail (tests : un schéma par base).
 */
export async function basePostgres({ connexion, schema, creerSchema = false, max = 5, ...options } = {}) {
  const { pg, types } = await analyseurs();
  const config = typeof connexion === 'string' ? { connectionString: connexion } : { ...configurationDepuisEnv(), ...(connexion ?? {}) };
  if (schema !== undefined && !MOTIF_SCHEMA.test(schema)) throw new Error(`Nom de schéma invalide : ${schema}`);
  if (schema && creerSchema) {
    const client = new pg.Client({ ...config, types });
    await client.connect();
    try {
      await client.query(`CREATE SCHEMA IF NOT EXISTS ${schema}`);
    } finally {
      await client.end();
    }
  }
  const pool = new pg.Pool({
    ...config,
    max,
    types,
    allowExitOnIdle: true,
    idleTimeoutMillis: 10_000,
    ...(schema ? { options: `-c search_path=${schema}` } : {}),
    ...options,
  });
  // Une connexion inactive coupée par le serveur ne doit pas faire tomber le processus.
  pool.on('error', e => console.error('[esport] postgres (connexion inactive)', e?.message ?? e));
  const cache = new Map();
  const traduire = sql => {
    let t = cache.get(sql);
    if (t === undefined) {
      t = traduireRequete(sql);
      if (cache.size < 2000) cache.set(sql, t);
    }
    return t;
  };
  const requete = (client, sql, params = []) => client.query({ text: traduire(sql), values: params.map(normaliser) });

  return {
    dialecte: 'postgres',
    // Schéma de travail (canal NOTIFY du temps réel : un par schéma).
    schema: schema ?? null,
    async tous(sql, params) {
      return (await requete(pool, sql, params)).rows;
    },
    async premier(sql, params) {
      return (await requete(pool, sql, params)).rows[0] ?? null;
    },
    async executer(sql, params) {
      return { changements: Number((await requete(pool, sql, params)).rowCount ?? 0) };
    },
    async lot(liste) {
      if (liste.length === 0) return [];
      const client = await pool.connect();
      const resultats = [];
      try {
        await client.query('BEGIN');
        for (const { sql, params = [] } of liste) resultats.push({ changements: Number((await requete(client, sql, params)).rowCount ?? 0) });
        await client.query('COMMIT');
      } catch (e) {
        await client.query('ROLLBACK').catch(() => {});
        throw e;
      } finally {
        client.release();
      }
      return resultats;
    },
    async script(sql) {
      // Protocole simple : plusieurs instructions, exécutées dans UNE transaction implicite (DDL transactionnel).
      await pool.query(traduireMigration(sql));
    },
    async fermer() {
      await pool.end();
    },
    pool,
  };
}

/** Base Postgres prête : ouverte et migrée (mêmes fichiers esport/migrations/*.sql, même migrateur). */
export async function basePostgresMigree(options = {}) {
  const base = await basePostgres(options);
  await appliquerMigrations(base, lireMigrations());
  return base;
}
