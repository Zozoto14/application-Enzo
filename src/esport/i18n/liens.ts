export type CleLi = keyof typeof fr;
const DICTIONNAIRES = { fr, en } as const;

/** Texte des liens dans la langue de l'app (clé inconnue : rendue telle quelle). */
export function trLi(cle: CleLi, vars?: Variables): string {
  return interpoler((DICTIONNAIRES[langueCourante()] as Record<string, string>)[cle] ?? fr[cle] ?? cle, vars);
}

/** Pluriel simple (« .one » / « .other ») : n = 1 → one. */
export function trnLi(cle: 'compte' | 'lies.n' | 'partage.fait' | 'ff.choisis' | 'ff.fini', n: number, vars?: Variables): string {
  return trLi(`${cle}.${n === 1 ? 'one' : 'other'}` as CleLi, { n, ...vars });
}
