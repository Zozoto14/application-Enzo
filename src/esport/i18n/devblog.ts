export type CleDv = keyof typeof fr;
const DICTIONNAIRES = { fr, en } as const;

/** Traduit une clé du devblog (clé inconnue : rendue telle quelle). */
export function trDv(cle: CleDv, vars?: Variables): string {
  return interpoler((DICTIONNAIRES[langueCourante()] as Record<string, string>)[cle] ?? (fr as Record<string, string>)[cle] ?? cle, vars);
}

type CleNombreDv = CleDv extends infer K ? (K extends `${infer B}.other` ? B : never) : never;

export function trnDv(cle: CleNombreDv, n: number, vars?: Variables): string {
  const k = `${cle}.${categoriePluriel(langueCourante(), n)}` as CleDv;
  return trDv(k, { n: formaterNombre(n), ...vars });
}
