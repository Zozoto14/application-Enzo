export type CleTk = keyof typeof fr;
const DICTIONNAIRES = { fr, en } as const;

/** Traduit une clé des tickets (clé inconnue : rendue telle quelle). */
export function trTk(cle: CleTk, vars?: Variables): string {
  return interpoler((DICTIONNAIRES[langueCourante()] as Record<string, string>)[cle] ?? (fr as Record<string, string>)[cle] ?? cle, vars);
}

type CleNombreTk = CleTk extends infer K ? (K extends `${infer B}.other` ? B : never) : never;

export function trnTk(cle: CleNombreTk, n: number, vars?: Variables): string {
  const k = `${cle}.${categoriePluriel(langueCourante(), n)}` as CleTk;
  return trTk(k, { n: formaterNombre(n), ...vars });
}
