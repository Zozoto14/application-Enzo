export type CleRe = keyof typeof fr;
const DICTIONNAIRES = { fr, en } as const;

/** Texte des réunions dans la langue de l'app (clé inconnue : rendue telle quelle). */
export function trRe(cle: CleRe, vars?: Variables): string {
  return interpoler((DICTIONNAIRES[langueCourante()] as Record<string, string>)[cle] ?? fr[cle] ?? cle, vars);
}

/** Pluriel simple (« .one » / « .other ») : n = 1 → one. */
export function trnRe(cle: 'agenda.a_repondre', n: number, vars?: Variables): string {
  return trRe(`${cle}.${n === 1 ? 'one' : 'other'}` as CleRe, { n, ...vars });
}
