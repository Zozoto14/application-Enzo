export type CleCompetition = keyof typeof fr;
const DICTIONNAIRES = { fr, en } as const;

/** Traduit une clé des écrans Tournois et Résultats (clé inconnue : rendue telle quelle). */
export function trC(cle: CleCompetition, vars?: Variables): string {
  return interpoler((DICTIONNAIRES[langueCourante()] as Record<string, string>)[cle] ?? (fr as Record<string, string>)[cle] ?? cle, vars);
}

type CleNombreCompetition = CleCompetition extends infer K ? (K extends `${infer B}.other` ? B : never) : never;

export function trnC(cle: CleNombreCompetition, n: number, vars?: Variables): string {
  const k = `${cle}.${categoriePluriel(langueCourante(), n)}` as CleCompetition;
  return trC(k, { n: formaterNombre(n), ...vars });
}
