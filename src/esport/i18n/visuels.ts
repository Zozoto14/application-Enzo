export type CleVi = keyof typeof fr;
const DICTIONNAIRES: Record<Langue, Record<string, string>> = { fr, en };

/** Texte des visuels dans une langue donnée (textes dessinés sur un visuel français ou anglais). */
export function trViLangue(langue: Langue, cle: CleVi, vars?: Variables): string {
  return interpoler(DICTIONNAIRES[langue][cle] ?? fr[cle] ?? cle, vars);
}

/** Texte des écrans des visuels dans la langue de l'app. */
export const trVi = (cle: CleVi, vars?: Variables): string => trViLangue(langueCourante(), cle, vars);
