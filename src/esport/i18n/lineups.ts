export type CleLu = keyof typeof fr;
const DICTIONNAIRES = { fr, en } as const;

/** Texte dans la langue de l'app (clé inconnue : rendue telle quelle). */
export function trLu(cle: CleLu, vars?: Variables): string {
  return interpoler((DICTIONNAIRES[langueCourante()] as Record<string, string>)[cle] ?? fr[cle] ?? cle, vars);
}

/** Pluriel simple (« .one » / « .other ») : n = 1 → one. */
export function trnLu(cle: 'filtres.n' | 'carte.sans_point' | 'strats.privees', n: number, vars?: Variables): string {
  return trLu(`${cle}.${n === 1 ? 'one' : 'other'}` as CleLu, { n, ...vars });
}

/** Clé adaptée au modèle du jeu quand elle existe (« titre.thefinals »), sinon la clé de base. */
export function trLuModele(cle: CleLu, modele: string | undefined, vars?: Variables): string {
  const propre = `${cle}.${modele ?? ''}`;
  return trLu((propre in fr ? propre : cle) as CleLu, vars);
}
