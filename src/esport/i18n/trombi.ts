export type CleTb = keyof typeof fr;
const DICTIONNAIRES = { fr, en } as const;

/** Traduit une clé du trombinoscope (clé inconnue : rendue telle quelle). */
export function trTb(cle: CleTb, vars?: Variables): string {
  return interpoler((DICTIONNAIRES[langueCourante()] as Record<string, string>)[cle] ?? (fr as Record<string, string>)[cle] ?? cle, vars);
}

type CleNombreTb = CleTb extends infer K ? (K extends `${infer B}.other` ? B : never) : never;

export function trnTb(cle: CleNombreTb, n: number, vars?: Variables): string {
  const k = `${cle}.${categoriePluriel(langueCourante(), n)}` as CleTb;
  return trTb(k, { n: formaterNombre(n), ...vars });
}
