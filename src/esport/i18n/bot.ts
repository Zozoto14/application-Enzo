export type CleBot = keyof typeof fr;
const DICTIONNAIRES = { fr, en } as const;

/** Traduit une clé du bot (clé inconnue : rendue telle quelle). */
export function trBot(cle: CleBot, vars?: Variables): string {
  return interpoler((DICTIONNAIRES[langueCourante()] as Record<string, string>)[cle] ?? (fr as Record<string, string>)[cle] ?? cle, vars);
}

/** Clé dynamique (permission, fonctionnalité déclarée par le serveur) : `defaut` si elle n'a pas de texte. */
export function trBotOu(cle: string, defaut: string, vars?: Variables): string {
  return cle in fr ? trBot(cle as CleBot, vars) : defaut;
}
