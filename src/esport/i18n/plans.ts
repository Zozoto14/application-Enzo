export type ClePm = keyof typeof fr;
const DICTIONNAIRES = { fr, en } as const;

/** Texte dans la langue de l'app (clé inconnue : rendue telle quelle). */
export function trPm(cle: ClePm, vars?: Variables): string {
  return interpoler((DICTIONNAIRES[langueCourante()] as Record<string, string>)[cle] ?? fr[cle] ?? cle, vars);
}

/** Pluriel simple (« .one » / « .other ») : n = 1 → one. */
export function trnPm(cle: 'liste.cartes', n: number, vars?: Variables): string {
  return trPm(`${cle}.${n === 1 ? 'one' : 'other'}` as ClePm, { n, ...vars });
}

/** Clé adaptée au modèle du jeu quand elle existe (« carte.ajouter.thefinals »), sinon la clé de base. */
export function trPmModele(cle: ClePm, modele: string | undefined, vars?: Variables): string {
  const propre = `${cle}.${modele ?? ''}`;
  return trPm((propre in fr ? propre : cle) as ClePm, vars);
}

/** Nom d'un side ou d'un mode dans un plan : attaque / défense traduits, clé d'un mode rendue lisible. */
export function nomSidePlan(side: string): string {
  if (side === '' || side === 'attaque' || side === 'defense') return trPm(`strats.side.${side}` as ClePm);
  return side.replace(/[-_]+/g, ' ').replace(/^./, c => c.toUpperCase());
}
