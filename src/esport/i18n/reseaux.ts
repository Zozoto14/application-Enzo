export type CleRs = keyof typeof fr;
const DICTIONNAIRES = { fr, en } as const;

/** Traduit une clé de la page Réseaux (clé inconnue : rendue telle quelle). */
export function trRs(cle: CleRs, vars?: Variables): string {
  return interpoler((DICTIONNAIRES[langueCourante()] as Record<string, string>)[cle] ?? (fr as Record<string, string>)[cle] ?? cle, vars);
}

type CleNombreRs = CleRs extends infer K ? (K extends `${infer B}.other` ? B : never) : never;

export function trnRs(cle: CleNombreRs, n: number, vars?: Variables): string {
  const k = `${cle}.${categoriePluriel(langueCourante(), n)}` as CleRs;
  return trRs(k, { n: formaterNombre(n), ...vars });
}

/** Libellé d'un champ d'import (métriques : leur nom ; autres : champ.*). */
export function libelleChamp(champ: string): string {
  const metrique: Record<string, CleRs> = {
    vues: 'metrique.vues',
    likes: 'metrique.likes',
    commentaires: 'metrique.commentaires',
    partages: 'metrique.partages',
    enregistrements: 'metrique.enregistrements',
    impressions: 'metrique.impressions',
    portee: 'metrique.portee',
    clics: 'metrique.clics',
    abonnes: 'metrique.abonnes',
    publications: 'metrique.publications',
  };
  const cle = metrique[champ] ?? (`champ.${champ}` as CleRs);
  return cle in fr ? trRs(cle) : champ;
}

/** Raison d'une ligne écartée à l'import. */
export function raisonImport(code: string): string {
  const cle = `raison.${code}` as CleRs;
  return cle in fr ? trRs(cle) : trRs('raison.valeur', { champ: libelleChamp(code) });
}
