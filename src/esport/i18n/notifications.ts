export type CleNf = keyof typeof fr;
const DICTIONNAIRES = { fr, en } as const;

/** Traduit une clé du centre de notifications (clé inconnue : rendue telle quelle). */
export function trNf(cle: CleNf, vars?: Variables): string {
  return interpoler((DICTIONNAIRES[langueCourante()] as Record<string, string>)[cle] ?? (fr as Record<string, string>)[cle] ?? cle, vars);
}

type CleNombreNf = CleNf extends infer K ? (K extends `${infer B}.other` ? B : never) : never;

export function trnNf(cle: CleNombreNf, n: number, vars?: Variables): string {
  const k = `${cle}.${categoriePluriel(langueCourante(), n)}` as CleNf;
  return trNf(k, { n: formaterNombre(n), ...vars });
}
